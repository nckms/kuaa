// A primeira alternativa é a correta; a rotação determinística espalha o gabarito.
function q(id: string, tags: string[], difficulty: 1 | 2 | 3, body: string,
  choices: [string, string, string, string, string], explanation: string): CuratedQuestion {
  const offset = Array.from(id).reduce((sum, char) => sum + char.charCodeAt(0), 0) % 5
  return {
    id: `kuaa-rev-${id}`, topicTags: tags, body, explanation, difficulty,
    options: choices.map((_, index) => {
      const source = (index + offset) % 5
      return { id: 'ABCDE'[index], text: choices[source], isCorrect: source === 0 }
    }),
  }
}

